function rune(body: ReactNode, cut?: ReactNode) {
  return function Icon(props: IconProps) {
    const id = useId();
    return (
      <svg
        viewBox="0 0 24 24"
        width={24}
        height={24}
        fill="none"
        aria-hidden
        {...props}
      >
        {cut ? (
          <>
            <mask
              id={id}
              maskUnits="userSpaceOnUse"
              x="0"
              y="0"
              width="24"
              height="24"
            >
              <rect width="24" height="24" fill="white" />
              {cut}
            </mask>
            <g mask={`url(#${id})`}>{body}</g>
          </>
        ) : (
          body
        )}
      </svg>
    );
  };
}

