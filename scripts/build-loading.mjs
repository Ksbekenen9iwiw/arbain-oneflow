import { createServer } from "vite";
import { mkdir, writeFile } from "node:fs/promises";

// Generate Django's first paint from the real Astryx components, not a CSS imitation.
const server = await createServer({
  server: { middlewareMode: true, watch: null, hmr: false, ws: false },
  appType: "custom",
});
try {
  const { renderLoading } = await server.ssrLoadModule(
    "/frontend/loading-prerender.tsx",
  );
  const directory = new URL("../crm/templates/crm/generated/", import.meta.url);
  await mkdir(directory, { recursive: true });
  for (const kind of ["dashboard", "list", "detail", "form", "login"]) {
    await writeFile(
      new URL(`loading-${kind}.html`, directory),
      `{# Generated by npm run build:loading from native Astryx components. #}\n${renderLoading(kind)}\n`,
    );
  }
} finally {
  await server.close();
}
