def classify_outlet(name: str):
    """Determine (outlet_type, discount_percent) from real Arba'in outlet naming conventions."""
    lower = name.lower()
    if lower.startswith('dj ') or 'grosir' in lower or 'gross' in lower or 'distributor' in lower:
        return 'DISTRIBUTOR', 25
    if (
        lower.startswith('tk ')
        or lower.startswith('toko ')
        or lower.startswith('sw ')
        or lower.startswith('swalayan ')
        or lower.startswith('kop ')
        or lower.startswith('koperasi ')
        or 'mart' in lower
        or 'swalayan' in lower
        or 'herbal' in lower
        or 'oleh-oleh' in lower
    ):
        return 'MINIMARKET', 20
    return 'APOTEK', 16
